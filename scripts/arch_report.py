#!/usr/bin/env python3
"""Generate `reports/architecture.md` — the measured state of the layering.

ADR-0040's C2: one script renders what the fitness gate measures, so the report
and the gate never disagree (it imports `arch_fitness`, the single source of the
layer table, the Part D map, A3's graph and the ratchets). The report carries
three things the restructuring prompt asks for:

  * lines per layer and per crate, and the CLI's lines by Part D destination;
  * the ratchet values against their baseline, and the open layer exceptions with
    the phase that closes each;
  * the inter-crate dependency graph, as Mermaid, read from the Cargo manifests.

Determinism: the output is a pure function of the tree (no wall clock), so the
diff against `main` is the architectural change and nothing else.

    python3 scripts/arch_report.py            # write reports/architecture.md
    python3 scripts/arch_report.py --check     # fail if it is out of date (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import arch_fitness as g  # noqa: E402

OUT = g.ROOT / "reports" / "architecture.md"

LAYER_ORDER = [g.FOUNDATION, g.CONTEXT, g.ADAPTER, g.PROVIDER, g.INTERFACE, g.ASSEMBLY, g.BIN]
LAYER_TITLE = {
    g.FOUNDATION: "foundation",
    g.CONTEXT: "context",
    g.ADAPTER: "adapter",
    g.PROVIDER: "provider",
    g.INTERFACE: "interface",
    g.ASSEMBLY: "assembly",
    g.BIN: "bin",
}


def _crate_dir_lines() -> dict[str, int]:
    return g.crate_rs_lines()


def _by_layer(lines: dict[str, int]) -> dict[str, list[tuple[str, int]]]:
    out: dict[str, list[tuple[str, int]]] = {lyr: [] for lyr in LAYER_ORDER}
    for name, n in lines.items():
        layer = g.LAYERS.get(name)
        if layer in out:
            out[layer].append((name, n))
    for lyr in out:
        out[lyr].sort(key=lambda x: -x[1])
    return out


def _cli_by_destination() -> list[tuple[str, int, int]]:
    """(destination, total lines, module count), context destinations first."""
    mods = g.cmd_module_lines()
    agg: dict[str, list[int]] = {}
    for m, n in mods.items():
        dest = g.CLI_DESTINATION.get(m, "(unmapped)")
        agg.setdefault(dest, [0, 0])
        agg[dest][0] += n
        agg[dest][1] += 1
    rows = [(d, v[0], v[1]) for d, v in agg.items()]
    rows.sort(key=lambda r: (r[0] not in g.CONTEXT_DESTINATIONS, -r[1]))
    return rows


def _mermaid(pkgs: dict[str, dict]) -> str:
    names = set(pkgs)
    lines = ["```mermaid", "graph LR"]
    layer_class = {
        g.FOUNDATION: "foundation", g.CONTEXT: "context", g.ADAPTER: "adapter",
        g.PROVIDER: "provider", g.INTERFACE: "interface", g.ASSEMBLY: "assembly",
        g.BIN: "bin",
    }
    for name in sorted(names):
        node = name.replace("-", "_")
        lines.append(f"  {node}[{name}]")
    for name in sorted(names):
        node = name.replace("-", "_")
        for dep in sorted(d["name"] for d in pkgs[name]["dependencies"] if d["kind"] is None):
            if dep in names:
                lines.append(f"  {node} --> {dep.replace('-', '_')}")
    for name in sorted(names):
        layer = g.LAYERS.get(name)
        if layer:
            lines.append(f"  class {name.replace('-', '_')} {layer_class[layer]};")
    lines += [
        "  classDef foundation fill:#e8f0fe,stroke:#4285f4;",
        "  classDef context fill:#e6f4ea,stroke:#34a853;",
        "  classDef adapter fill:#fef7e0,stroke:#fbbc04;",
        "  classDef provider fill:#fce8e6,stroke:#ea4335;",
        "  classDef interface fill:#f3e8fd,stroke:#a142f4;",
        "  classDef assembly fill:#e0f7fa,stroke:#00acc1;",
        "  classDef bin fill:#e8eaed,stroke:#5f6368;",
        "```",
    ]
    return "\n".join(lines)


def render() -> str:
    pkgs = g.crates()
    lines = _crate_dir_lines()
    by_layer = _by_layer(lines)
    base = json.loads(g.BASELINE.read_text(encoding="utf-8"))

    cli_ctx, _ = g.cli_destination_map()
    iface_mech, iface_where = g.interface_mechanism_deps(pkgs)
    prov_namers, _ = g.provider_namers(pkgs)
    n_bins, bin_names = g.bin_crates(pkgs)
    ctx_viol, ctx_where = g.inter_context_violations(pkgs)
    self_exec = g.count(g.SELF_EXEC)[0]
    prints = g.count(g.PRINTS)[0]
    env_writes = g.count(g.ENV_WRITES, skip_bin=False)[0]

    out: list[str] = []
    w = out.append
    w("# Architecture report — the measured layering")
    w("")
    w("> Generated by `scripts/arch_report.py` (ADR-0040 C2). A pure function of the")
    w("> tree: the diff against `main` is the architectural change, nothing else.")
    w("")

    total = sum(lines.values())
    w("## Lines per layer")
    w("")
    w("| Layer | Crates | Lines | Share |")
    w("| --- | ---: | ---: | ---: |")
    for lyr in LAYER_ORDER:
        rows = by_layer[lyr]
        s = sum(n for _, n in rows)
        share = f"{s / total * 100:.1f}%" if total else "—"
        w(f"| {LAYER_TITLE[lyr]} | {len(rows)} | {s:,} | {share} |")
    w(f"| **total** | **{len(lines)}** | **{total:,}** | 100% |")
    w("")

    w("## Lines per crate")
    w("")
    for lyr in LAYER_ORDER:
        rows = by_layer[lyr]
        if not rows:
            continue
        w(f"### {LAYER_TITLE[lyr]}")
        w("")
        w("| Crate | Lines |")
        w("| --- | ---: |")
        for name, n in rows:
            flag = " ⚠️ >20k" if n > g.SIZE_LIMIT else ""
            w(f"| {name}{flag} | {n:,} |")
        w("")

    w("## CLI lines by Part D destination")
    w("")
    w("Where each `bins/delonix/src/cmd` module's business rule goes.")
    w("Context destinations (the `cli_context_lines` ratchet) come first.")
    w("")
    w("| Destination | Lines | Modules | Context? |")
    w("| --- | ---: | ---: | :---: |")
    for dest, n, c in _cli_by_destination():
        is_ctx = "✓" if dest in g.CONTEXT_DESTINATIONS else ""
        w(f"| {dest} | {n:,} | {c} | {is_ctx} |")
    w(f"| **context total** | **{cli_ctx:,}** | | |")
    w("")

    w("## Ratchets")
    w("")
    w("Each entered at its value on `64a5953a`; the gate fails if any rises, or")
    w("falls without the baseline lowered in the same commit.")
    w("")
    w("| Ratchet | Now | Baseline | Target |")
    w("| --- | ---: | ---: | --- |")
    targets = {
        "cli_context_lines": "0 (R4)",
        "interface_mechanism_deps": "0 (R3)",
        "provider_namers": "0 (R3/R4)",
        "bin_crates": "1 (R1)",
        "inter_context_violations": "0 (R2)",
        "self_exec_sites": "0 (R5)",
        "library_prints": "down",
        "env_writes": "down",
        "shared_error_imports": "0",
        "raw_error_variant_matches": "0",
        "context_spawns": "0",
    }
    now = {
        "cli_context_lines": cli_ctx,
        "interface_mechanism_deps": iface_mech,
        "provider_namers": prov_namers,
        "bin_crates": n_bins,
        "inter_context_violations": ctx_viol,
        "self_exec_sites": self_exec,
        "library_prints": prints,
        "env_writes": env_writes,
    }
    for key in base:
        v = now.get(key, base[key])
        w(f"| {key} | {v:,} | {base[key]:,} | {targets.get(key, '—')} |")
    w("")

    w("## Open layer exceptions")
    w("")
    w("Each names the phase that removes it (an exception with no phase fails the gate).")
    w("")
    w("| From | To | Phase | Why |")
    w("| --- | --- | :---: | --- |")
    for (kind, a, b), (phase, reason) in sorted(g.EXCEPTIONS.items()):
        w(f"| {a} | {b} | {phase} | {reason} |")
    w("")

    if ctx_where or iface_where:
        w("## What the ratchets still point at")
        w("")
        if ctx_where:
            w("Inter-context edges outside A3 (closed in R2):")
            w("")
            for e in ctx_where:
                w(f"- `{e}`")
            w("")
        if iface_where:
            w("Interface → adapter/provider (closed in R3):")
            w("")
            for e in iface_where:
                w(f"- `{e}`")
            w("")

    w("## Crate dependency graph")
    w("")
    w(_mermaid(pkgs))
    w("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if reports/architecture.md is stale")
    args = ap.parse_args()
    content = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print("reports/architecture.md is stale — run: python3 scripts/arch_report.py")
            return 1
        print("ok    reports/architecture.md is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(g.ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
