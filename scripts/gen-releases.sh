#!/usr/bin/env bash
# Gera docs/RELEASES.md — o apêndice "features por release" — a partir de
# docs/releases/<tag>.md (uma nota por release, a MESMA publicada no GitHub
# Releases; a 1.ª linha é o título). Determinístico e idempotente: corre
# localmente ou no workflow de release (que o comita no main a cada tag).
set -euo pipefail
cd "$(dirname "$0")/.."
out=docs/RELEASES.md
{
  # The header is the published appendix, so it follows LANG-01 (English): a
  # Portuguese header here is re-emitted on every tag by the release workflow,
  # whatever a hand edit of docs/RELEASES.md said (5d0d5947 did exactly that).
  echo "# Delonix Runtime — features by release"
  echo
  echo "> Generated by \`scripts/gen-releases.sh\` from \`docs/releases/<tag>.md\`"
  echo "> (automatically regenerated by the release pipeline on every published tag)."
  echo "> Do not edit by hand — edit the respective release note."
  echo
  for f in $(ls docs/releases/v*.md | sort -rV); do
    cat "$f"
    echo
    echo "---"
    echo
  done
} > "$out"
echo "gerado: $out ($(grep -c '^## ' "$out") releases)"
